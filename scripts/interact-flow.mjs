import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on("console", (m) => ["error", "warning"].includes(m.type()) && errs.push(m.text().slice(0, 200)));
p.on("pageerror", (e) => errs.push(e.message));
await p.addInitScript(() => sessionStorage.setItem("spike-ignited", "1"));
await p.goto(`${process.argv[2] ?? "http://localhost:3000"}/#colecao`, { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.click("text=FERRARI 812 SUPERFAST");
await p.waitForTimeout(1200);
await p.getByRole("button", { name: "Personalizar no Ateliê" }).click();
await p.waitForTimeout(1600);
console.log("hash:", await p.evaluate(() => location.hash), "| carro no seletor:", await p.locator("select").first().inputValue());
await p.getByRole("radio", { name: /Black Label/ }).click();
await p.getByRole("switch", { name: /Spike Guard/ }).click();
await p.getByRole("switch", { name: /Spike Care/ }).click();
await p.waitForTimeout(1200);
const total = await p.locator("text=Total estimado").locator("..").locator(".sr-only").textContent();
console.log("total:", total);
await p.screenshot({ path: "qa/shots/flow-atelie.png" });
await p.getByRole("button", { name: "Agendar com esta configuração" }).click();
await p.waitForTimeout(1600);
console.log("hash:", await p.evaluate(() => location.hash));
await p.getByRole("button", { name: "Solicitar visita privada" }).click();
await p.waitForTimeout(300);
console.log("erros visíveis:", await p.locator("[aria-invalid=true]").count(), "| foco:", await p.evaluate(() => document.activeElement?.getAttribute("autocomplete")));
await p.fill("input[autocomplete=name]", "Ana Teste");
await p.fill("input[type=tel]", "11987654321");
console.log("máscara:", await p.inputValue("input[type=tel]"));
await p.fill("input[type=email]", "ana@exemplo.com");
await p.check("input[type=checkbox]");
await p.screenshot({ path: "qa/shots/flow-concierge-filled.png" });
await p.getByRole("button", { name: "Solicitar visita privada" }).click();
await p.waitForTimeout(1200);
console.log("sucesso:", await p.locator("text=Recebido.").count());
await p.screenshot({ path: "qa/shots/flow-concierge-ok.png" });
// teclado: 1..6 e setas
await p.keyboard.press("2");
await p.waitForTimeout(1300);
console.log("tecla 2 ->", await p.evaluate(() => location.hash));
await p.keyboard.press("ArrowRight");
await p.waitForTimeout(1300);
console.log("seta -> ", await p.evaluate(() => location.hash), "| foco:", await p.evaluate(() => document.activeElement?.id));
await p.mouse.move(700, 450);
await p.mouse.wheel(0, 400);
await p.waitForTimeout(1500);
console.log("roda ->", await p.evaluate(() => location.hash));
console.log("status:", await p.locator("[role=status][aria-live=polite]").last().textContent());
console.log(errs.length ? errs.join("\n") : "sem erros");
await b.close();
