import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.addInitScript(() => sessionStorage.setItem("spike-ignited", "1"));
await p.goto("http://localhost:3100/#colecao", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
await p.click("text=MCLAREN 720S");
await p.waitForTimeout(400);
await p.screenshot({ path: "qa/shots/colecao-wipe-mid.png" });
await p.waitForTimeout(1500);
await p.mouse.move(780, 520);
await p.waitForTimeout(1600);
await p.screenshot({ path: "qa/shots/colecao-blueprint.png" });
await p.click("text=Ver ficha completa");
await p.waitForTimeout(1200);
await p.screenshot({ path: "qa/shots/colecao-drawer.png" });
await p.keyboard.press("Escape");
await p.waitForTimeout(900);
console.log("drawer gone:", (await p.$('[role=dialog][aria-modal=true]')) === null, "hash:", await p.evaluate(() => location.hash));
await b.close();
